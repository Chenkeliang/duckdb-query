"""共享的安全文件名原语。

把用户可控的名字清洗成安全的文件名主干:去掉路径分隔符/引号/控制字符,strip 掉
首尾的点与空格(挡住 `..` 穿越与隐藏名),限长 100。任何要落到磁盘路径、或拼进
DuckDB `COPY ... TO '...'` 的文件名都应先过这里——同时防路径穿越和 SQL 字符串
打断。空 / 清洗后为空返回空串,由调用方决定回退名。

历史上下载(async_tasks)与集合导出(set_operations)各写过一份等价实现,导出那份
漏了清洗、可被 filename 穿越并注入 COPY;统一到本模块避免再次漂移。
"""

import re


def safe_filename_base(name: str) -> str:
    """清洗成安全的文件名主干(不含扩展名);空/清洗后为空则返回空串。"""
    if not name:
        return ""
    # 保留中英文/数字/下划线/连字符/点/空格;其余(含 / \ ' " 等)替换为下划线,
    # 再 strip 掉首尾的点与空格,使 "../../x" 无分隔符残留、无法逃出目标目录。
    cleaned = re.sub(r"[^\w一-鿿.\- ]", "_", str(name)).strip(" .")
    return cleaned[:100]
